# -*- coding: utf-8 -*-
"""Render the slide HTML to 1920x1080 PNGs, one per reveal state.

Text accuracy is the whole point of these two frames, so they are rendered from
HTML rather than generated by an image model.
"""
import os
import sys
from playwright.sync_api import sync_playwright

sys.stdout.reconfigure(encoding='utf-8')
HERE = os.path.dirname(os.path.abspath(__file__))

JOBS = [
    ('ethics_slide.html',    'ethics',   [0, 1, 2, 3]),
    ('pipeline_diagram.html', 'pipeline', [1, 2, 3, 4]),
]

with sync_playwright() as p:
    browser = p.chromium.launch()
    page = browser.new_page(viewport={'width': 1920, 'height': 1080},
                            device_scale_factor=1)
    for html, stem, reveals in JOBS:
        url = 'file:///' + os.path.join(HERE, html).replace('\\', '/')
        for r in reveals:
            page.goto(f'{url}?reveal={r}', wait_until='networkidle')
            page.wait_for_timeout(1200)          # let webfonts settle
            out = os.path.join(HERE, f'{stem}_{r}.png')
            page.screenshot(path=out)
            print(f'{os.path.basename(out)}  {os.path.getsize(out)//1024} KB')
    browser.close()
print('done')
