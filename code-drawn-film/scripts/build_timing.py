"""Turn a shot plan + the real narration durations into src/timing.js and work/timeline.json.

  py build_timing.py --plan script/plan.json --voice work/voice/manifest.json

plan.json: [{"shot": "c01_open", "min": 24, "lines": [["s01", 9.0]], "tail": 3}, ...]
  - shots run back to back from t = 0 in the order given
  - each line starts at `offset` seconds into its shot; an offset may be "after:<id>+<gap>" to start
    <gap> seconds after an earlier line of the same shot ends
  - a shot lasts max(min, last line end + tail)
Writes window.TIMING = {dur, shots: {name: {t0, t1}}, lines: {id: {t0, t1, text}}} and the narration
part of the mix timeline (music and sfx are added by the film's own mix plan). Prints a table.
"""
import argparse, json, pathlib, sys
sys.stdout.reconfigure(encoding="utf-8")

ap = argparse.ArgumentParser(); ap.add_argument("--plan", required=True); ap.add_argument("--voice", required=True)
ap.add_argument("--js", default="src/timing.js"); ap.add_argument("--timeline", default="work/timeline.json")
a = ap.parse_args()
plan = json.loads(pathlib.Path(a.plan).read_text(encoding="utf-8"))
man = json.loads(pathlib.Path(a.voice).read_text(encoding="utf-8"))
vdir = pathlib.Path(a.voice).parent
t, shots, lines, nar = 0.0, {}, {}, []
for s in plan:
    ends = {}
    for lid, off in s.get("lines", []):
        if lid not in man:
            sys.exit("line %s is not in %s" % (lid, a.voice))
        if isinstance(off, str) and off.startswith("after:"):
            ref, gap = off[6:].split("+"); off = ends[ref] + float(gap)
        start = t + float(off); end = start + man[lid]["duration"]; ends[lid] = end - t
        lines[lid] = {"t0": round(start, 3), "t1": round(end, 3), "text": man[lid]["text"], "shot": s["shot"]}
        nar.append({"file": str(vdir / (lid + ".wav")).replace("\\", "/"), "t": round(start, 3)})
    dur = max(s.get("min", 0), (max(ends.values()) + s.get("tail", 1.5)) if ends else 0)
    shots[s["shot"]] = {"t0": round(t, 3), "t1": round(t + dur, 3)}
    t += dur
T = {"dur": round(t, 3), "shots": shots, "lines": lines}
pathlib.Path(a.js).write_text("// generated by build_timing.py from %s + %s - do not edit by hand\nwindow.TIMING = %s;\n"
                              % (a.plan, a.voice, json.dumps(T, ensure_ascii=False, indent=1)), encoding="utf-8")
tl_p = pathlib.Path(a.timeline); tl = json.loads(tl_p.read_text(encoding="utf-8")) if tl_p.exists() else {}
tl.update({"dur": T["dur"], "narration": nar}); tl_p.parent.mkdir(parents=True, exist_ok=True)
tl_p.write_text(json.dumps(tl, ensure_ascii=False, indent=1), encoding="utf-8")
for name, s in shots.items():
    ls = [k for k, v in lines.items() if v["shot"] == name]
    print("%-14s %7.2f - %7.2f  (%5.2fs)  %s" % (name, s["t0"], s["t1"], s["t1"] - s["t0"], " ".join(ls)))
print("total %.2fs (%d:%04.1f) | wrote %s and %s" % (t, int(t // 60), t % 60, a.js, a.timeline))
